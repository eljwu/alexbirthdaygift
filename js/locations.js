/* --------------------------------
   MAP INITIALIZATION
-------------------------------- */

const map =
  L.map(
    "map",
    {
      zoomControl: true,
      minZoom: 3
    }
  );


L.tileLayer(
  "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png",
  {
    maxZoom: 19,

    attribution:
      '&copy; OpenStreetMap contributors'
  }
).addTo(map);


/* Start with national view */

map.setView(
  [
    39.5,
    -96
  ],
  4
);


/* --------------------------------
   CUSTOM ICONS
-------------------------------- */

const normalIcon =
  L.divIcon({
    className: "",

    html:
      '<div class="location-marker"></div>',

    iconSize:
      [22, 22],

    iconAnchor:
      [11, 11]
  });


const starIcon =
  L.divIcon({
    className: "",

    html:
      '<div class="ann-arbor-marker">★</div>',

    iconSize:
      [40, 40],

    iconAnchor:
      [20, 20]
  });


/* --------------------------------
   MARKER GROUPS
-------------------------------- */

const nationalLayer =
  L.layerGroup()
    .addTo(map);


const annArborLayer =
  L.layerGroup();


/* --------------------------------
   NATIONAL MARKERS
-------------------------------- */

Object.values(
  nationalLocations
).forEach(location => {

  const marker =
    L.marker(
      location.coordinates,
      {
        icon: normalIcon
      }
    );


  marker.bindTooltip(
    location.name,
    {
      direction: "top",
      offset: [0, -10]
    }
  );


  marker.on(
    "click",
    () => {

      showLocation(
        location
      );

    }
  );


  marker.addTo(
    nationalLayer
  );

});


/* --------------------------------
   ANN ARBOR STAR
-------------------------------- */

const annArborMarker =
  L.marker(
    annArbor.coordinates,
    {
      icon: starIcon
    }
  );


annArborMarker.bindTooltip(
  "Ann Arbor — Primary Base",
  {
    direction: "top",
    offset: [0, -15]
  }
);


annArborMarker.on(
  "click",
  () => {

    enterAnnArbor();

  }
);


annArborMarker.addTo(
  nationalLayer
);


