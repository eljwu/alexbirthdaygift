/* --------------------------------
   LOCATION PANEL
-------------------------------- */

function showLocation(
  location
) {

  emptyLocation.classList.add(
    "hidden"
  );

  locationContent.classList.remove(
    "hidden"
  );


  locationName.textContent =
    location.name;

  locationCode.textContent =
    location.code;

  locationDescription.textContent =
    location.description;


  createGallery(
    location.photos
  );

}


/* --------------------------------
   GALLERY
-------------------------------- */

function createGallery(
  photos
) {

  thumbnails.innerHTML =
    "";


  photoCount.textContent =
    `${photos.length} FILES`;


  setMainPhoto(
    photos[0]
  );


  photos.forEach(
    (photo, index) => {

      const button =
        document.createElement(
          "button"
        );


      button.type =
        "button";


      button.className =
        "thumbnail";


      if (index === 0) {

        button.classList.add(
          "selected"
        );

      }


      /*
        Placeholder support.

        When photo is an actual image
        filename, we'll show the image.
      */

      if (
        photo.includes("/") ||
        photo.includes(".jpg") ||
        photo.includes(".jpeg") ||
        photo.includes(".png") ||
        photo.includes(".webp")
      ) {

        const image =
          document.createElement(
            "img"
          );

        image.src =
          photo;

        image.alt =
          "";

        button.appendChild(
          image
        );

      } else {

        button.textContent =
          photo;

      }


      button.addEventListener(
        "click",
        () => {

          document
            .querySelectorAll(
              ".thumbnail"
            )
            .forEach(item => {

              item.classList.remove(
                "selected"
              );

            });


          button.classList.add(
            "selected"
          );


          setMainPhoto(
            photo
          );

        }
      );


      thumbnails.appendChild(
        button
      );

    }
  );

}


/* --------------------------------
   MAIN PHOTO
-------------------------------- */

function setMainPhoto(
  photo
) {

  mainPhoto.innerHTML =
    "";


  if (
    photo.includes("/") ||
    photo.includes(".jpg") ||
    photo.includes(".jpeg") ||
    photo.includes(".png") ||
    photo.includes(".webp")
  ) {

    const image =
      document.createElement(
        "img"
      );


    image.src =
      photo;

    image.alt =
      "Location memory";


    mainPhoto.appendChild(
      image
    );

  } else {

    mainPhoto.textContent =
      photo;

  }

}


/* --------------------------------
   ENTER ANN ARBOR
-------------------------------- */

function enterAnnArbor() {

  nationalLayer.removeFrom(
    map
  );


  annArborLayer.addTo(
    map
  );


  mapViewLabel.textContent =
    "ANN ARBOR, MICHIGAN";


  backButton.classList.remove(
    "hidden"
  );


  resetPanel();


  map.flyTo(
    annArbor.coordinates,
    13,
    {
      duration: 1.4
    }
  );

}


